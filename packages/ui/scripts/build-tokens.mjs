/**
 * Generates the Tailwind v4 theme (src/theme.css) and a typed token object (src/tokens.ts)
 * from brand/tokens/empire-noir.json — the single source of truth for colours, radii and fonts
 * (handbook/DESIGN_SYSTEM.md, D-023, D-024).
 *
 * Usage: `pnpm --filter @empire/ui tokens` (write) or `tokens:check` (CI: fail if stale).
 *
 * DO NOT CHANGE: the CSS variable names (`--color-*`, `--radius-*`, `--font-*`, `--text-*`).
 * Tailwind derives utility classes from them (bg-noir-900, rounded-card, font-display…) and
 * every component and page uses those classes. Renaming a token breaks styling silently.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../../brand/tokens/empire-noir.json");
const cssOut = resolve(here, "../src/theme.css");
const tsOut = resolve(here, "../src/tokens.ts");
const check = process.argv.includes("--check");

const t = JSON.parse(readFileSync(source, "utf8"));
const header =
  "GENERATED by packages/ui/scripts/build-tokens.mjs from brand/tokens/empire-noir.json — do not edit.\n" +
  "Change the JSON, then run `pnpm --filter @empire/ui tokens`.";

// WHY: @fontsource-variable/manrope registers the family as "Manrope Variable"; the token keeps the
// plain family name so other tools (Figma, email) stay readable. Prepend the variable family here.
const fontSans = `"Manrope Variable", ${t.font.sans}`;

const lines = [];
lines.push(`/* ${header.replace(/\n/g, "\n * ")} */`, "", "@theme {");
lines.push("  /* Colours */");
for (const [k, v] of Object.entries(t.color)) lines.push(`  --color-${k}: ${v};`);
lines.push("  /* Lead pipeline stages (CMS) */");
for (const [stage, parts] of Object.entries(t.stage)) {
  for (const [part, v] of Object.entries(parts)) {
    lines.push(`  --color-stage-${stage.replace(/_/g, "-")}-${part}: ${v};`);
  }
}
lines.push("  /* Fonts */");
lines.push(`  --font-display: ${t.font.display};`);
lines.push(`  --font-sans: ${fontSans};`);
lines.push("  /* Type scale */");
for (const [k, v] of Object.entries(t.fontSize)) {
  // WHY: Tailwind's `text-*` utility reads both --color-* and --text-*. A name used by both
  // (today only "body") would make `text-body` ambiguous, so the size is skipped here; 16 px body
  // text is Tailwind's default `text-base`.
  if (k in t.color) continue;
  lines.push(`  --text-${k}: ${v};`);
}
lines.push("  /* Radii */");
for (const [k, v] of Object.entries(t.radius)) lines.push(`  --radius-${k}: ${v};`);
// WHY: the token spacing scale (4 px steps) equals Tailwind's default `--spacing: 0.25rem`,
// so it is not re-declared — p-1 = 4 px, p-2 = 8 px … already match handbook/DESIGN_SYSTEM.md §4.
lines.push(`  --ease-brand: ${t.motion.easing};`);
lines.push("}", "");
lines.push("/* Values that are not Tailwind namespaces, exposed as plain custom properties. */");
lines.push(":root {");
lines.push(`  --gradient-metallic: ${t.gradient.metallic};`);
lines.push(`  --gradient-hairline: ${t.gradient.hairline};`);
lines.push(`  --focus-ring: ${t.focus.ring};`);
lines.push(`  --focus-offset: ${t.focus.offset};`);
lines.push(`  --motion-fast: ${t.motion.fast};`);
lines.push(`  --motion-base: ${t.motion.base};`);
lines.push(`  --layout-container: ${t.layout.container};`);
lines.push(`  --layout-touch-min: ${t.layout["touch-min"]};`);
lines.push("}", "");
lines.push("@media (prefers-reduced-motion: reduce) {");
lines.push("  :root {");
lines.push("    --motion-fast: 0ms;");
lines.push("    --motion-base: 0ms;");
lines.push("  }");
lines.push("}", "");
const css = lines.join("\n");

const ts =
  `/* ${header.replace(/\n/g, "\n * ")} */\n\n` +
  `export const tokens = ${JSON.stringify({ ...t, $meta: undefined }, null, 2)} as const;\n\n` +
  "export type ColorToken = keyof typeof tokens.color;\n";

if (check) {
  const stale = [
    [cssOut, css],
    [tsOut, ts],
  ].filter(([path, body]) => {
    try {
      return readFileSync(path, "utf8") !== body;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error("Design tokens are stale. Run: pnpm --filter @empire/ui tokens");
    process.exit(1);
  }
  console.log("Design tokens are up to date.");
} else {
  writeFileSync(cssOut, css);
  writeFileSync(tsOut, ts);
  console.log("Wrote", cssOut, "and", tsOut);
}
