/**
 * Generates src/schema.d.ts (TypeScript types for every API path) from an OpenAPI document.
 *
 * Usage:
 *   pnpm --filter @empire/api-client generate                 # from ./openapi.json (exported by the API)
 *   pnpm --filter @empire/api-client generate -- <path>       # from another file, e.g. the design contract
 *   pnpm --filter @empire/api-client generate:check           # CI: fail if schema.d.ts is stale
 *
 * The API is the source of truth from Phase 3 (D-020): `pnpm api:openapi` writes ./openapi.json
 * from the FastAPI app, then this script turns it into types. CI runs both and fails on a diff.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2).filter((a) => a !== "--" && !a.startsWith("--"));
const check = process.argv.includes("--check");
const input = resolve(process.cwd(), args[0] ?? resolve(here, "../openapi.json"));
const output = resolve(here, "../src/schema.d.ts");

if (!existsSync(input)) {
  console.error(
    `OpenAPI file not found: ${input}\n` +
      "Export it from the API first (`pnpm api:openapi`) or pass a path, e.g. ../../handbook/api/openapi-v1.yaml",
  );
  process.exit(1);
}

const ast = await openapiTS(pathToFileURL(input));
const header =
  "/**\n" +
  " * GENERATED by packages/api-client/scripts/generate.mjs — do not edit by hand.\n" +
  " * Regenerate: `pnpm api:openapi && pnpm api:client` (handbook/CONTRIBUTING.md §9).\n" +
  " */\n\n";
const body = header + astToString(ast);

if (check) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : "";
  if (current !== body) {
    console.error("src/schema.d.ts is stale. Run: pnpm api:openapi && pnpm api:client");
    process.exit(1);
  }
  console.log("API client types are up to date.");
} else {
  writeFileSync(output, body);
  console.log(`Wrote ${output} from ${input}`);
}
