def main() -> None:
    words = {(base + suffix).lower() for base in BASES for suffix in SUFFIXES}
    words |= {p.lower() for p in PATTERNS}
    kept = sorted(w for w in words if len(w) >= 12)
    out = Path(__file__).resolve().parents[1] / "src/empire_api/users/common_passwords.txt"
    header = "# Generated by scripts/make_common_passwords.py — do not edit by hand.\n"
    out.write_text(header + "\n".join(kept) + "\n", encoding="utf-8")
    print(f"wrote {len(kept)} entries to {out}")  # noqa: T201


if __name__ == "__main__":
    main()
