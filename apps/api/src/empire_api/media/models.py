"""Tables of the media module: the library (`media`), signed direct uploads (`upload_intent`)
and the links that attach a library item to an owner (`media_link`).

Collaborators: migrations/versions/0003_media.py creates exactly these tables
(tests/test_migrations.py fails on any drift); library.py, uploads.py and links.py are the only
writers.
Implements: ARCHITECTURE §6 (exclusive arc, one cover per owner and role), §12 (media),
SECURITY.md §6 (one intent per signed upload).

INVARIANT: a link has exactly one owner (`ck_media_link_one_owner`), real foreign keys cascade
when the owner is deleted, and a library item can't be deleted while a link points at it
(RESTRICT; library.delete_media answers 409 first).
INVARIANT: one cover per owner and role, at most one link per owner in a single-valued role,
and the same file only once per owner and role (indexes below; vocab.SINGLE_ROLES).
"""

from __future__ import annotations

import uuid
from datetime import date, datetime
from decimal import Decimal

from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    ForeignKey,
    Index,
    Numeric,
    String,
    UniqueConstraint,
    func,
)
from sqlalchemy import text as sql
from sqlalchemy.orm import Mapped, mapped_column, relationship

from empire_api.db import Base, created_at_column, uuid_pk
from empire_api.media.vocab import (
    LINK_ROLES,
    MEDIA_KINDS,
    MEDIA_LABELS,
    RESOURCE_TYPES,
    ROLES_BY_OWNER,
    SINGLE_ROLES,
    STORE_NAMES,
)
from empire_api.projects.vocab import check_in

# One column per owner type in the exclusive arc (ARCHITECTURE §6). Phase 4 part 4 added
# `page_id` and `post_id` (migrations/versions/0005_content.py).
OWNER_COLUMNS = ("project_id", "configuration_id", "construction_update_id", "page_id", "post_id")


def _per_owner_indexes() -> list[Index]:
    """One cover per owner and role, and one link per owner in each of its single-valued roles
    (a project's brochure, RERA QR, hero and share image; a configuration's floor plan)."""
    indexes: list[Index] = []
    for column in OWNER_COLUMNS:
        owner = column.removesuffix("_id")
        indexes.append(
            Index(
                f"uq_media_link_{owner}_cover",
                column,
                "role",
                unique=True,
                postgresql_where=sql(f"is_cover AND {column} IS NOT NULL"),
            )
        )
        singles = sorted(SINGLE_ROLES & set(ROLES_BY_OWNER[owner]))
        if not singles:
            continue
        quoted = ", ".join(f"'{role}'" for role in singles)
        indexes.append(
            Index(
                f"uq_media_link_{owner}_single_role",
                column,
                "role",
                unique=True,
                postgresql_where=sql(f"role IN ({quoted}) AND {column} IS NOT NULL"),
            )
        )
    return indexes


class Media(Base):
    """One file in the library. The file lives at the store; this row is its record."""

    __tablename__ = "media"

    id: Mapped[uuid.UUID] = uuid_pk()
    kind: Mapped[str] = mapped_column(String(10))
    store: Mapped[str] = mapped_column(String(12))
    # Generated by us (empire/<APP_ENV>/<kind>/<uuid7>); the uploaded filename is never used.
    public_id: Mapped[str] = mapped_column(String(255), unique=True)
    resource_type: Mapped[str] = mapped_column(String(8))
    version: Mapped[int] = mapped_column(BigInteger)
    format: Mapped[str] = mapped_column(String(10))
    bytes: Mapped[int] = mapped_column(BigInteger)
    width: Mapped[int | None] = mapped_column()
    height: Mapped[int | None] = mapped_column()
    duration_s: Mapped[Decimal | None] = mapped_column(Numeric(10, 2))
    title: Mapped[str] = mapped_column(String(160))
    alt_text: Mapped[str | None] = mapped_column(String(250))
    label: Mapped[str | None] = mapped_column(String(20))
    label_month: Mapped[date | None] = mapped_column()  # always the first day of the month
    is_sample: Mapped[bool] = mapped_column(server_default=sql("false"))
    # WHY no foreign key: like project.created_by, authorship outlives any staff account row.
    created_by: Mapped[uuid.UUID | None] = mapped_column()
    created_at: Mapped[datetime] = created_at_column()
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())

    __table_args__ = (
        Index("ix_media_created_at", sql("created_at DESC")),
        CheckConstraint(check_in("kind", MEDIA_KINDS), name="kind_valid"),
        CheckConstraint(check_in("store", STORE_NAMES), name="store_valid"),
        CheckConstraint(check_in("resource_type", RESOURCE_TYPES), name="resource_type_valid"),
        CheckConstraint(check_in("label", MEDIA_LABELS), name="label_valid"),
        CheckConstraint("bytes >= 0", name="bytes_not_negative"),
        # COMPLIANCE: a progress photo always says which month it shows; documents have no label.
        CheckConstraint(
            "label IS DISTINCT FROM 'progress_photo' OR label_month IS NOT NULL",
            name="progress_photo_has_month",
        ),
        CheckConstraint(
            "label_month IS NULL OR label IN ('actual_photo', 'progress_photo')",
            name="label_month_needs_dated_label",
        ),
        CheckConstraint(
            "label_month IS NULL OR EXTRACT(DAY FROM label_month) = 1",
            name="label_month_first_day",
        ),
        CheckConstraint("kind <> 'document' OR label IS NULL", name="document_has_no_label"),
    )


class UploadIntent(Base):
    """One signed direct upload (video or document) waiting to be confirmed.

    SECURITY: `confirm` only accepts a reply whose public id matches an unexpired, unused intent
    created by the same user, and marks it used in the same transaction. So nobody can confirm
    someone else's upload or replay a reply (SECURITY.md §6). The daily clean-up deletes old
    rows (integrations/outbox_drain.cleanup).
    """

    __tablename__ = "upload_intent"

    id: Mapped[uuid.UUID] = uuid_pk()
    public_id: Mapped[str] = mapped_column(String(255), unique=True)
    kind: Mapped[str] = mapped_column(String(10))
    resource_type: Mapped[str] = mapped_column(String(8))
    max_bytes: Mapped[int] = mapped_column(BigInteger)
    created_by: Mapped[uuid.UUID] = mapped_column()
    created_at: Mapped[datetime] = created_at_column()
    expires_at: Mapped[datetime] = mapped_column(index=True)
    used_at: Mapped[datetime | None] = mapped_column()

    __table_args__ = (
        CheckConstraint("kind IN ('video', 'document')", name="kind_valid"),
        CheckConstraint(check_in("resource_type", RESOURCE_TYPES), name="resource_type_valid"),
    )


class MediaLink(Base):
    """A library item attached to one owner in one role, with its order and website switches."""

    __tablename__ = "media_link"

    id: Mapped[uuid.UUID] = uuid_pk()
    # WHY RESTRICT (the default): a file in use can't vanish from a project page.
    media_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("media.id"), index=True)
    project_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("project.id", ondelete="CASCADE")
    )
    configuration_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("configuration.id", ondelete="CASCADE")
    )
    construction_update_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("construction_update.id", ondelete="CASCADE")
    )
    page_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("page.id", ondelete="CASCADE"))
    post_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("post.id", ondelete="CASCADE"))
    role: Mapped[str] = mapped_column(String(12))
    sort_order: Mapped[int] = mapped_column(server_default=sql("0"))
    is_cover: Mapped[bool] = mapped_column(server_default=sql("false"))
    is_visible: Mapped[bool] = mapped_column(server_default=sql("true"))
    created_by: Mapped[uuid.UUID | None] = mapped_column()
    created_at: Mapped[datetime] = created_at_column()
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())

    media: Mapped[Media] = relationship(lazy="joined")

    __table_args__ = (
        CheckConstraint(
            "num_nonnulls(project_id, configuration_id, construction_update_id, page_id, "
            "post_id) = 1",
            name="one_owner",
        ),
        CheckConstraint(check_in("role", LINK_ROLES), name="role_valid"),
        # INVARIANT: hidden items can't be the cover (links.update_link unpins on hide).
        CheckConstraint("is_visible OR NOT is_cover", name="cover_is_visible"),
        # The same file once per owner and role. Each also indexes its owner's foreign key.
        UniqueConstraint("project_id", "role", "media_id"),
        UniqueConstraint("configuration_id", "role", "media_id"),
        UniqueConstraint("construction_update_id", "role", "media_id"),
        UniqueConstraint("page_id", "role", "media_id"),
        UniqueConstraint("post_id", "role", "media_id"),
        *_per_owner_indexes(),
    )
